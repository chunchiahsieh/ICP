const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
let text = '1\r\n2\r\n1', count = '', reloads = 0;
const handlers = {};
const input = { val(v) { if (arguments.length) { text = v; return this; } return text; }, is() { return true; } };
const filter = { length: 1, find(selector) { return selector === '.filter-count' ? {text(v) {count=v;}} : selector === '[data-bs-toggle="dropdown"]' ? [] : input; }, data() {return 'Text';}, closest() {return this;} };
const scope = {find() {return filter;}};
const doc = {};
const events = {off() {return this;}, on(name, selector, handler) {handlers[name]=handler; return this;}};
const button = {closest() {return filter;}};
function $(obj) {return obj === doc ? events : obj;}
$.each = (obj, callback) => Object.entries(obj).forEach(([key, value]) => callback(key, value));
const context = {window: {jQuery: $}, document: doc};
vm.runInNewContext(fs.readFileSync(path.join(root,'ICP/wwwroot/js/pro-table-filters.js'),'utf8'),context);
const api = context.window.ProTableFilters;
const map = { invoiceFilter: {fieldName:'InvoiceNo',filterType:'Text'} };
const saved = api.getProTableFilterValues(scope,map);
assert.equal(saved.invoiceFilter.text,text);
assert.equal(api.buildProTableQueryPayload(saved,map)['Text[InvoiceNo]'],text);
api.updateAllProTableFilterCounts(scope,map);
assert.equal(count,'(2)');
text=''; api.restoreProTableFilterValues(saved,scope,map);
assert.equal(text,'1\r\n2\r\n1');
api.bindProTableFilterActions({pageSelector:'.report-page',resolveReload:()=>()=>reloads++});
handlers['click.proTableFilterReset'].call(button,{preventDefault(){},stopPropagation(){}});
assert.equal(text,''); assert.equal(count,'(0)'); assert.equal(reloads,1);
console.log('PASS multiline payload, restore, unique count, reset and reload');
