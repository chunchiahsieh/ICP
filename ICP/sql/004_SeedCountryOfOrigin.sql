(
    Category,
    FunctionCode,
    Key1,
    Key2,
    Value1,
    Value2,
    Value3,
    Value4,
    Value5,
    Value6,
    IsDeleted,
    CreateTime,
    CreateUser,
    UpdateTime,
    UpdateUser
)
