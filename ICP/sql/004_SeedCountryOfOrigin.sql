    @Category,
    NULL,
    source.Key1,
    N'',
    source.Value1,
    NULL,
    NULL,
    NULL,
    NULL,
    NULL,
    0,
    @Now,
    @Actor,
    NULL,
    NULL
FROM @Source AS source
WHERE NOT EXISTS
(
    SELECT 1
    FROM dbo.SystemConfigs AS target WITH (UPDLOCK, HOLDLOCK)
    WHERE target.Category = @Category
      AND target.FunctionCode IS NULL
      AND target.Key1 = source.Key1
      AND target.Key2 = N''
      AND target.IsDeleted = 0
);

